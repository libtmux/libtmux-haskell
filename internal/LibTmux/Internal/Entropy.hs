{-# LANGUAGE CApiFFI #-}
-- | Fixed-size, nonblocking entropy for endpoint generations and frames.
module LibTmux.Internal.Entropy (freshToken32, EntropyError (..)) where

import Control.Exception (Exception, throwIO)
import Control.Monad (unless)
import Data.ByteString (ByteString)
import Data.ByteString qualified as Bytes
import Data.Word (Word8)
import Foreign.C.Error (throwErrnoIfMinus1)
import Foreign.C.Types (CSize (..), CUInt (..))
import Foreign.Marshal.Alloc (allocaBytes)
import Foreign.Ptr (Ptr, castPtr)
import System.Posix.Types (CSsize (..))

foreign import capi unsafe "sys/random.h getrandom"
  getRandom :: Ptr Word8 -> CSize -> CUInt -> IO CSsize

foreign import capi "sys/random.h value GRND_NONBLOCK"
  randomNonblocking :: CUInt

data EntropyError = ShortEntropy
  deriving stock (Eq, Show)
instance Exception EntropyError

-- | Copy exactly 32 OS-generated bytes. Errno and short reads fail explicitly.
freshToken32 :: IO ByteString
freshToken32 = allocaBytes 32 $ \buffer -> do
  count <- throwErrnoIfMinus1 "libtmux entropy" (getRandom buffer 32 randomNonblocking)
  unless (count == 32) (throwIO ShortEntropy)
  Bytes.packCStringLen (castPtr buffer, 32)
