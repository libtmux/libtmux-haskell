def page(body: str) -> str:
    """A Haddock 2.33.0 page around ``body``."""
    return (
        "<!DOCTYPE html><html><body>"
        + body
        + '<div id="footer">Generated by Haddock version 2.33.0</div></body></html>'
    )


def record(owner: str) -> str:
    """A record type whose field ``ref`` has the same name in every record."""
    return (
        f'<div class="top"><p class="src">data <a id="t:{owner}" class="def">{owner}</a></p>'
        '<div class="subs fields"><ul><li><dfn class="src">'
        '<a id="v:ref" class="def">ref</a> :: !Integer</dfn>'
        '<div class="doc"><p>Kept &amp; exact.</p></div></li></ul></div></div>'
    )


def browser_files(raw: Path, body: str) -> None:
    """Write a minimal native artifact whose page holds ``body``."""
    raw.mkdir(parents=True, exist_ok=True)
    files = {
        PAGE: page(body),
        "meta.json": '{"haddock_version":"2.33.0","quickjump_version":1}',
        "doc-index.json": "[]",
        "haddock-bundle.min.js": "",
        "quick-jump.min.js": "",
        "quick-jump.css": "",
        "linuwial.css": "body {background: url(synopsis.png)}",
        "synopsis.png": "fixture",
        "haskell-logo.svg": "<svg></svg>",
    }
    for name, content in files.items():
        (raw / name).write_text(content)


class Links(HTMLParser):
    """The ids, links and listing text of a page, for comparing before and after."""

    def __init__(self, text: str) -> None:
        super().__init__()
        self.ids: list[str] = []
        self.hrefs: list[str] = []
        self.pre: list[str] = []
        self.viewports: list[str | None] = []
        self.pre_attributes: list[dict[str, str | None]] = []
        self.in_pre = False
        self.feed(text)

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        attributes = dict(attrs)
        if "id" in attributes and attributes["id"] is not None:
            self.ids.append(attributes["id"])
        if tag == "a" and attributes.get("href") is not None:
            self.hrefs.append(str(attributes["href"]))
        if tag == "pre":
            self.in_pre = True
            self.pre_attributes.append(attributes)
        if tag == "meta" and attributes.get("name") == "viewport":
            self.viewports.append(attributes.get("content"))

    def handle_endtag(self, tag: str) -> None:
        if tag == "pre":
            self.in_pre = False

    def handle_data(self, data: str) -> None:
        if self.in_pre:
            self.pre.append(data)


