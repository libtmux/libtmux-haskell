def test_each_record_field_and_synopsis_reaches_its_owner(prepare_html: PrepareHtml) -> None:
    """Same-named fields get owner-qualified anchors, in the body and the synopsis."""
    owners = ["Session", "Window", "Pane"]
    synopsis = (
        '<div id="synopsis"><ul>'
        + "".join(
            f'<li class="src short">data <a href="#t:{owner}">{owner}</a>'
            ' {<ul class="subs"><li><a href="#v:ref">ref</a> :: !Integer</li></ul>}</li>'
            for owner in owners
        )
        + "</ul></div>"
    )
    raw = page(synopsis + '<div id="interface">' + "".join(map(record, owners)) + "</div>")
    result = prepare_html({PAGE: raw})[PAGE]
    parsed = Links(result)
    for owner in owners:
        assert f"v:{owner}.ref" in parsed.ids
        assert f"#v:{owner}.ref" in parsed.hrefs
    assert parsed.ids.count("v:ref") == 1
    assert len(parsed.ids) == len(set(parsed.ids))
    assert "Kept &amp; exact." in result


def test_owner_free_index_link_retains_a_choice_of_all_records(prepare_html: PrepareHtml) -> None:
    """The index link to a bare field name keeps one destination per owner."""
    index = '<html><body><a href="LibTmux-Snapshot.html#v:ref">ref</a></body></html>'
    result = prepare_html(
        {PAGE: page(record("Session") + record("Window")), "doc-index.html": index}
    )
    assert result["doc-index.html"] == index
    assert "Session.ref" in result[PAGE]
    assert "Window.ref" in result[PAGE]
    assert Links(result[PAGE]).ids.count("v:ref") == 1


def test_instance_methods_have_distinct_instance_local_targets(prepare_html: PrepareHtml) -> None:
    """The same method in two instances gets one anchor per instance."""

    def instance(owner: str) -> str:
        return (
            f'<details id="i:id:{owner}:Eq:1"><div class="subs methods"><p class="src">'
            '<a href="#v:-61--61-">(==)</a> :: Bool '
            '<a href="#v:-61--61-" class="selflink">#</a></p></div></details>'
        )

    result = prepare_html({PAGE: page(instance("Session") + instance("Window"))})[PAGE]
    parsed = Links(result)
    for owner in ["Session", "Window"]:
        anchor = f"m:i:id:{owner}:Eq:1:v:-61--61-"
        assert anchor in parsed.ids
        assert parsed.hrefs.count("#" + anchor) == 2


def test_method_parameter_links_are_not_method_binders(prepare_html: PrepareHtml) -> None:
    """Only the leading link of a method signature is its binder."""
    body = (
        '<a id="t:Session"></a><details id="i:id:Session:Eq:1">'
        '<div class="subs methods"><p class="src">'
        '<a href="#v:-61--61-">(==)</a> :: <a href="#t:Session">Session</a>'
        ' -&gt; Bool <a href="#v:-61--61-" class="selflink">#</a>'
        "</p></div></details>"
    )
    result = prepare_html({PAGE: page(body)})[PAGE]
    assert "#m:i:id:Session:Eq:1:v:-61--61-" in Links(result).hrefs
    assert "#t:Session" in Links(result).hrefs


def test_source_collisions_preserve_text_and_offer_distinct_lines(
    prepare_html: PrepareHtml,
) -> None:
    """Colliding source anchors keep the listing text and become line choices."""
    source = (
        '<html><body><pre><span id="line-4"><a id="Thing"></a><a id="Thing"></a>'
        'data Thing</span>\n<span id="line-5"><a id="ref"></a>ref :: Integer</span>\n'
        '<span id="line-9"><a id="ref"></a>ref :: Text</span></pre>'
        '<a href="#ref">ref</a></body></html>'
    )
    result = prepare_html({PAGE: page(f'<a href="{SOURCE}#Thing">Source</a>'), SOURCE: source})
    parsed = Links(result[SOURCE])
    assert parsed.pre == Links(source).pre
    assert parsed.ids.count("Thing") == 1
    assert parsed.ids.count("ref") == 1
    assert "#line-5" in parsed.hrefs
    assert "#line-9" in parsed.hrefs
    assert len(parsed.ids) == len(set(parsed.ids))


