def test_hidden_attribution_keeps_text_and_source_link(prepare_html: PrepareHtml) -> None:
    """A link to a hidden module becomes plain text; its source link survives."""
    body = (
        '<div class="instances"><details id="i:id:X:Eq:1">'
        '<p>Defined in <a href="LibTmux-Internal-Graph.html">LibTmux.Internal.Graph</a></p>'
        f'<a class="link" href="{SOURCE}#line-4">Source</a></details></div>'
    )
    raw = page(body)
    source = '<html><body><pre><span id="line-4">data X</span></pre></body></html>'
    result = prepare_html({PAGE: raw, SOURCE: source})
    assert result[PAGE] == raw.replace(
        '<a href="LibTmux-Internal-Graph.html">LibTmux.Internal.Graph</a>',
        "LibTmux.Internal.Graph",
    )
    assert Links(result[SOURCE]).pre == Links(source).pre
    assert Links(result[SOURCE]).ids == Links(source).ids
    assert Links(result[SOURCE]).hrefs == Links(source).hrefs


