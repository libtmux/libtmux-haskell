def test_copy_preserves_raw_and_exposes_no_failed_output(tmp_path: Path, manifest: Path) -> None:
    """The raw artifact stays byte-identical, and a failed run leaves no output directory."""
    raw, output = tmp_path / "raw", tmp_path / "prepared"
    browser_files(raw, "")
    original = page(record("Session") + record("Window")).encode()
    (raw / PAGE).write_bytes(original)
    original_style = (raw / "linuwial.css").read_bytes()
    source = (
        '<html><head><link rel="stylesheet" href="style.css">'
        '<script src="highlight.js"></script></head><body><pre>'
        '<span id="line-1">data X = X\n</span></pre></body></html>'
    )
    (raw / "src").mkdir()
    (raw / SOURCE).write_text(source)
    original_source_style = b"body {color: black}"
    (raw / "src/style.css").write_bytes(original_source_style)
    original_source_script = b"void 0;"
    (raw / "src/highlight.js").write_bytes(original_source_script)
    (raw / "interface.haddock").write_bytes(b"unchanged compiled interface\x00")
    tool.prepare(raw, output, manifest)
    assert (raw / PAGE).read_bytes() == original
    assert (raw / "linuwial.css").read_bytes() == original_style
    assert (output / "linuwial.css").read_bytes().startswith(original_style)
    assert (raw / SOURCE).read_text() == source
    assert (raw / "src/style.css").read_bytes() == original_source_style
    assert (raw / "src/highlight.js").read_bytes() == original_source_script
    assert (output / "src/highlight.js").read_bytes().startswith(original_source_script)
    assert (output / "src/style.css").read_bytes() != original_source_style
    prepared_source = Links((output / SOURCE).read_text())
    assert prepared_source.pre == Links(source).pre
    assert prepared_source.ids == Links(source).ids
    assert prepared_source.viewports == ["width=device-width, initial-scale=1"]
    assert prepared_source.pre_attributes == [
        {"tabindex": "0", "role": "region", "aria-label": "Haskell source"}
    ]
    assert (output / "interface.haddock").read_bytes() == b"unchanged compiled interface\x00"
    evidence = json.loads((output / "navigation.json").read_text())
    entry = next(item for item in evidence["files"] if item["path"] == PAGE)
    assert entry["rawSha256"] == hashlib.sha256(original).hexdigest()
    assert entry["rawSha256"] != entry["preparedSha256"]
    style = next(item for item in evidence["files"] if item["path"] == "linuwial.css")
    assert style["rawSha256"] == hashlib.sha256(original_style).hexdigest()
    prepared_style = hashlib.sha256((output / "linuwial.css").read_bytes()).hexdigest()
    assert style["preparedSha256"] == prepared_style
    with pytest.raises(ValueError, match="exist"):
        tool.prepare(raw, output, manifest)
    (raw / "broken.html").write_text('<a href="missing.html">bad</a>')
    failed = tmp_path / "failed"
    with pytest.raises(ValueError, match=r"missing|Missing"):
        tool.prepare(raw, failed, manifest)
    assert not failed.exists()
    assert (raw / PAGE).read_bytes() == original


