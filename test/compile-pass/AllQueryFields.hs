{-# LANGUAGE OverloadedRecordDot #-}
module AllQueryFields where

import Data.Text (Text)
import LibTmux.Query qualified as Q
import LibTmux.Query.Fields qualified as F
import LibTmux.Snapshot
  ( Session, Window, Pane (currentCommand, currentPath), WindowLink, PaneOccurrence
  , Client (name, tty), ClientAttachment, ServerInfo (socketPath), TmuxText
  )
import LibTmux.Id (SessionId, WindowId, PaneId)
import LibTmux.Value (Dimension, PaneIndex, WindowIndex)
import LibTmux.Version (TmuxVersion)

publicSignatures :: [()]
publicSignatures =
  [ check (F.sessionId :: Q.Field Session SessionId)
  , check (F.sessionName :: Q.Field Session Text)
  , check (F.sessionAttached :: Q.Field Session Integer)
  , check (F.sessionGroup :: Q.Field Session (Maybe TmuxText))
  , check (F.sessionWindowLinks :: Q.ToMany Session WindowLink)
  , check (F.sessionClients :: Q.ToMany Session Client)
  , check (F.windowId :: Q.Field Window WindowId)
  , check (F.windowName :: Q.Field Window TmuxText)
  , check (F.windowWidth :: Q.Field Window Dimension)
  , check (F.windowHeight :: Q.Field Window Dimension)
  , check (F.windowLayout :: Q.Field Window Text)
  , check (F.windowZoomed :: Q.Field Window Bool)
  , check (F.windowPanes :: Q.ToMany Window Pane)
  , check (F.windowLinks :: Q.ToMany Window WindowLink)
  , check (F.paneId :: Q.Field Pane PaneId)
  , check (F.paneWindowId :: Q.Field Pane WindowId)
  , check (F.paneIndex :: Q.Field Pane PaneIndex)
  , check (F.paneWidth :: Q.Field Pane Dimension)
  , check (F.paneHeight :: Q.Field Pane Dimension)
  , check (F.paneActive :: Q.Field Pane Bool)
  , check (F.paneDead :: Q.Field Pane Bool)
  , check (F.paneTitle :: Q.Field Pane Text)
  , checkField F.paneCurrentCommand (\(row :: Pane) -> row.currentCommand)
  , checkField F.paneCurrentPath (\(row :: Pane) -> row.currentPath)
  , check (F.paneCursorX :: Q.Field Pane Integer)
  , check (F.paneCursorY :: Q.Field Pane Integer)
  , check (F.paneModeCount :: Q.Field Pane Integer)
  , check (F.paneMode :: Q.Field Pane (Maybe Text))
  , check (F.paneWindow :: Q.ToOne Pane Window)
  , check (F.linkSessionId :: Q.Field WindowLink SessionId)
  , check (F.linkWindowId :: Q.Field WindowLink WindowId)
  , check (F.linkIndex :: Q.Field WindowLink WindowIndex)
  , check (F.linkActive :: Q.Field WindowLink Bool)
  , check (F.linkFlags :: Q.Field WindowLink Text)
  , check (F.linkSession :: Q.ToOne WindowLink Session)
  , check (F.linkWindow :: Q.ToOne WindowLink Window)
  , check (F.linkPanes :: Q.ToMany WindowLink Pane)
  , check (F.occurrencePane :: Q.ToOne PaneOccurrence Pane)
  , check (F.occurrenceLink :: Q.ToOne PaneOccurrence WindowLink)
  , checkField F.clientName (\(row :: Client) -> row.name)
  , check (F.clientPid :: Q.Field Client Integer)
  , checkField F.clientTty (\(row :: Client) -> row.tty)
  , check (F.clientWidth :: Q.Field Client Integer)
  , check (F.clientHeight :: Q.Field Client (Maybe Integer))
  , check (F.clientAttachment :: Q.ToOptional Client ClientAttachment)
  , check (F.clientAttachmentSessionId :: Q.Field ClientAttachment SessionId)
  , check (F.clientAttachmentWindowId :: Q.Field ClientAttachment WindowId)
  , check (F.clientAttachmentWindowIndex :: Q.Field ClientAttachment WindowIndex)
  , check (F.clientAttachmentPaneId :: Q.Field ClientAttachment PaneId)
  , check (F.clientAttachmentSession :: Q.ToOne ClientAttachment Session)
  , check (F.clientAttachmentWindow :: Q.ToOne ClientAttachment Window)
  , check (F.clientAttachmentPane :: Q.ToOne ClientAttachment PaneOccurrence)
  , check (F.serverInfoPid :: Q.Field ServerInfo Integer)
  , check (F.serverInfoStartedAt :: Q.Field ServerInfo Integer)
  , check (F.serverInfoVersion :: Q.Field ServerInfo TmuxVersion)
  , checkField F.serverInfoSocketPath (\(row :: ServerInfo) -> row.socketPath)
  ]

check :: description -> ()
check _ = ()

checkField :: Q.Field row value -> (row -> value) -> ()
checkField _ _ = ()
